import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..');
const read=(p)=>fs.readFileSync(path.join(root,p),'utf8');
const html=read('index.html');
const manifest=JSON.parse(read('manifest.webmanifest'));
const plan=JSON.parse(read('plan.json'));
const script=read('app.js');
assert(html.includes('lang="de"'));
for(const file of ['app.js','styles.css','plan.json','manifest.webmanifest','sw.js','icon.svg','icon-192.png','icon-512.png']) assert(fs.existsSync(path.join(root,file)),`missing ${file}`);
for(const ref of ['./styles.css','./app.js','./manifest.webmanifest','./icon.svg']) assert(html.includes(ref),`index reference missing: ${ref}`);
for(const icon of manifest.icons) assert(fs.existsSync(path.join(root,icon.src)),`icon missing: ${icon.src}`);
assert.equal(manifest.display,'standalone');
assert.equal(manifest.scope,'./');
assert.equal(manifest.start_url,'./');
assert.equal(plan.sessions.length,55);
assert.equal(plan.sessions.filter(x=>x.week<=13).length,52);
assert.equal(plan.sessions.filter(x=>x.week===14).length,3);
const ids=plan.sessions.map(x=>x.id); assert.equal(new Set(ids).size,ids.length,'duplicate IDs');
assert(!script.includes('form-hyrox-trainer-v1'),'independent Anna data storage expected');
assert(script.includes('validateImportedData'),'import safety missing');
assert(script.includes('anna-hyrox2-preimport-v1'),'preimport backup missing');
console.log('PASS: PWA links, install manifest, icons, independent storage, import guard, 55 unique plan entries');
